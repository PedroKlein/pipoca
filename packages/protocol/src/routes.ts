// The layers under every Profile, which work alike: the admin's base
// Profile (ADR 0044) and each person's My defaults (ADR 0063).
function layer<const Path extends string>(path: Path) {
  const files = `${path}/files` as const;
  const file = `${path}/files/*path` as const;

  return {
    get: { method: "GET", path, auth: "person" },
    update: {
      method: "PUT",
      path,
      auth: "person",
      body: any,
      changes: ["profiles"],
    },
    files: { method: "GET", path: files, auth: "person" },
    upload: {
      method: "POST",
      path: files,
      auth: "person",
      body: uploadedFiles,
      status: 204,
      changes: ["profiles"],
    },
    file: { method: "GET", path: file, auth: "person", response: "bytes" },
    write: {
      method: "PUT",
      path: file,
      auth: "person",
      body: "bytes",
      status: 204,
      changes: ["profiles"],
    },
    remove: {
      method: "DELETE",
      path: file,
      auth: "person",
      status: 204,
      changes: ["profiles"],
    },
  } as const;
}

